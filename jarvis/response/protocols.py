@dataclass(frozen=True)
class Question:
    id: str
    ask: str
    if_no: str        # what to do before answering yes


@dataclass(frozen=True)
class Protocol:
    id: str
    title: str
    brief: str
    jobs: tuple                     # collectors whose fresh runs verify it
    resolves: tuple                 # (job, exact title | title prefix ending in "…")
    steps: tuple
    requires: tuple = ()
    questions: tuple = ()
    alternative: tuple = ()         # the same result by command, for the terminal-inclined
    caution: str = ""
    # Remediation graph: steps and their dependencies
    # Each entry: step_name -> [prerequisite_step_names]
    remediation_edges: Dict[str, List[str]] = field(default_factory=dict)

    def fixes(self, job, finding):
        title = (finding or {}).get("title") or ""
        for owner, pattern in self.resolves:
            if owner != job:
                continue
            if pattern.endswith("…") and title.startswith(pattern[:-1]):
                return True
            if title == pattern:
                return True
        return False


