// Writes tests/fixtures/licence/vectors.json: shared test vectors for the worker (TypeScript) and the
// Argus client (Python). Test-only keys, made fresh each run; nothing here is used in production.
//   bun scripts/make-vectors.ts
import { writeFileSync } from "node:fs";
import { b64url, signJws, signedMessage } from "../src/cert";
import { ALPHABET, base32, checkChar, formatKey } from "../src/keys";

const rnd = (n: number) => crypto.getRandomValues(new Uint8Array(n));
const check: [string, string][] = [];
for (let i = 0; i < 40; i++) { const body = (i % 2 ? "SRV" : "DSK") + base32(rnd(15), 24); check.push([body, checkChar(body)]); }
const k1 = formatKey("SERVER", base32(rnd(15), 24)), k2 = formatKey("DESKTOP", base32(rnd(15), 24));
const typo = k1.slice(0, -1) + ALPHABET[(ALPHABET.indexOf(k1.at(-1)!) + 1) % 32];
const parse: [string, string | null][] = [
  [k1, k1], [k1.toLowerCase(), k1], [k1.replace(/-/g, " "), k1], [k1.replace("ARGUS-", ""), k1], [k2.toLowerCase().replace(/-/g, ""), k2],
  [typo, null], ["ARGUS-SERVER-1C285B2D-6CE6-4BC7-B8BE-ADB6A7E304DA", null], ["", null], ["ARGUS-SRV-", null],
];

// Ed25519: a PKCS#8 test key. The 32-byte seed is the last 32 bytes of the PKCS#8 DER.
const pair = (await crypto.subtle.generateKey({ name: "Ed25519" }, true, ["sign", "verify"])) as CryptoKeyPair;
const pkcs8 = new Uint8Array(await crypto.subtle.exportKey("pkcs8", pair.privateKey) as ArrayBuffer);
const pub = b64url(new Uint8Array(await crypto.subtle.exportKey("raw", pair.publicKey) as ArrayBuffer));
const message = signedMessage("renew", "act_0123456789ABCDEFGHJK", "bm9uY2Vub25jZW5vbmNl", 1762300000);
const sig = b64url(await crypto.subtle.sign("Ed25519", pair.privateKey, new TextEncoder().encode(message)));
const claims = { iss: "pay.archymedes.xyz", aud: "argus", sub: "lic_TEST", plan: "server", seats: 1, act: "act_0123456789ABCDEFGHJK",
                 dev: "ab".repeat(32), dpk: pub, iat: 1762300000, exp: 1764892000, lic_exp: 1793836000, renew_after: 1764287200 };
const jws = await signJws(`vec-k1.${b64url(pkcs8)}`, claims);

writeFileSync(new URL("../../../tests/fixtures/licence/vectors.json", import.meta.url), JSON.stringify({
  note: "Generated by hosted/licence-cloudflare/scripts/make-vectors.ts. Test-only keys.",
  check, parse,
  ed25519: { seed: b64url(pkcs8.slice(-32)), pub, message, sig },
  jws: { kid: "vec-k1", pub, token: jws, claims },
}, null, 1) + "\n");
console.log("wrote tests/fixtures/licence/vectors.json");
