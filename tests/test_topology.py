"""Host topology: structural explanations for WSL runtime processes, renamed
system helpers and the WSL DNS tunnel. Every missing fact must leave the
original finding in place."""

import os
import stat
import subprocess
import tempfile
import unittest
from unittest import mock

from jarvis.collectors.process import detect
from jarvis.collectors.process.hidden.run import _orphan_finding
from jarvis.platform import topology

# Not /tmp: the suite runs on the protected host (see test_hidden_attribution).
SCRATCH = os.path.join(os.path.expanduser("~"), ".cache", "jarvis-tests")

FIB = """Main:
  +-- 0.0.0.0/0 3 0 5
     |-- 10.255.255.254
        /32 host LOCAL
Local:
     |-- 127.0.0.1
        /32 host LOCAL
"""
RESOLV = ("# This file was automatically generated by WSL. To stop automatic "
          "generation of this file, add the following entry to /etc/wsl.conf:\n"
          "nameserver 10.255.255.254\n")


class FakeHost:
    """A fake /proc + /etc + /init tree. Only file identity (dev, ino) and
    mode matter to the code under test, so ownership is patched per test."""

    def __init__(self, testcase, osrelease="6.6.0-microsoft-standard-WSL2",
                 init_mount="ro"):
        os.makedirs(SCRATCH, mode=0o700, exist_ok=True)
        self.tmp = tempfile.TemporaryDirectory(dir=SCRATCH)
        testcase.addCleanup(self.tmp.cleanup)
        root = self.tmp.name
        self.proc = os.path.join(root, "proc")
        self.etc = os.path.join(root, "etc")
        self.init = os.path.join(root, "init")
        self.bin = os.path.join(root, "usr", "bin")
        for d in (self.proc, self.etc, self.bin,
                  os.path.join(self.proc, "self"), os.path.join(self.proc, "sys", "kernel"),
                  os.path.join(self.proc, "net")):
            os.makedirs(d, exist_ok=True)
        self._write(self.init, "init")
        os.chmod(self.init, 0o755)
        self._write(os.path.join(self.proc, "sys", "kernel", "osrelease"), osrelease)
        self._write(os.path.join(self.proc, "self", "mountinfo"),
                    f"111 82 0:2 /init {self.init} {init_mount} - rootfs rootfs rw\n")
        self._write(os.path.join(self.proc, "net", "fib_trie"), FIB)
        self._write(os.path.join(self.etc, "resolv.conf"), RESOLV)

    @staticmethod
    def _write(path, text):
        with open(path, "w") as fh:
            fh.write(text)

    def binary(self, name, mode=0o755):
        path = os.path.join(self.bin, name)
        self._write(path, name)
        os.chmod(path, mode)
        return path

    def process(self, pid, comm, exe, ppid, uid=0):
        d = os.path.join(self.proc, str(pid))
        os.makedirs(d, exist_ok=True)
        os.symlink(exe, os.path.join(d, "exe"))
        self._write(os.path.join(d, "comm"), comm[:15] + "\n")
        self._write(os.path.join(d, "status"),
                    f"Name:\t{comm[:15]}\nPPid:\t{ppid}\nUid:\t{uid}\t{uid}\t{uid}\t{uid}\n")

    def topo(self):
        return topology.snapshot(proc=self.proc, etc=self.etc, init=self.init)


def rec(pid, name, exe, cmdline=None, user="root", script=""):
    return {"host": "wsl", "pid": pid, "name": name, "exe": exe, "script": script,
            "cmdline": cmdline or exe, "user": user, "conns": [], "fp": f"fp{pid}"}


def as_root(func):
    """Files in the fake tree belong to the test user; the code requires root
    ownership. Pretend every stat reports uid 0, keeping dev/ino/mode real."""
    real = os.stat

    def fake(path, *a, **kw):
        st = real(path, *a, **kw)
        return os.stat_result((st.st_mode, st.st_ino, st.st_dev, st.st_nlink, 0,
                               st.st_gid, st.st_size, st.st_atime, st.st_mtime, st.st_ctime))

    def wrapper(*a, **kw):
        with mock.patch.object(topology.os, "stat", side_effect=fake):
            return func(*a, **kw)
    return wrapper


class WslRuntimeTests(unittest.TestCase):
    def setUp(self):
        self.host = FakeHost(self)
        h = self.host
        h.process(2, "init-systemd(Ubuntu)", h.init, 0)
        h.process(2385, "SessionLeader", h.init, 2)
        h.process(2386, "Relay(2387)", h.init, 2385)

    @as_root
    def test_session_leader_and_relay_are_the_wsl_runtime(self):
        topo = self.host.topo()
        for pid, name in ((2385, "SessionLeader"), (2386, "Relay(2387)")):
            p = rec(pid, name, self.host.init)
            self.assertIn("WSL /init runtime", topology.wsl_runtime(p, topo))
            self.assertNotIn("name-mismatch", detect.traits(p, topo))

    @as_root
    def test_systemd_distro_layout_ends_the_chain_at_pid_one(self):
        # Measured on this host: systemd is pid 1 and WSL's init-systemd is
        # pid 2 with PPid 1; the session leaders hang below pid 2.
        host = FakeHost(self)
        systemd = host.binary("systemd")
        host.process(1, "systemd", systemd, 0)
        host.process(2, "init-systemd(Ubuntu)", host.init, 1)
        host.process(2385, "SessionLeader", host.init, 2)
        host.process(2386, "Relay(2387)", host.init, 2385)
        topo = host.topo()
        for pid, name in ((2385, "SessionLeader"), (2386, "Relay(2387)")):
            self.assertIn("WSL /init runtime",
                          topology.wsl_runtime(rec(pid, name, host.init), topo))

    @as_root
    def test_init_started_by_a_shell_under_pid_one_is_not_the_runtime(self):
        host = FakeHost(self)
        host.process(1, "systemd", host.binary("systemd"), 0)
        host.process(400, "bash", host.binary("bash"), 1)
        host.process(401, "SessionLeader", host.init, 400)
        self.assertIsNone(topology.wsl_runtime(rec(401, "SessionLeader", host.init),
                                               host.topo()))

    @as_root
    def test_non_root_init_in_the_chain_breaks_the_proof(self):
        host = FakeHost(self)
        host.process(1, "systemd", host.binary("systemd"), 0)
        host.process(2, "init-systemd(Ubuntu)", host.init, 1, uid=1000)
        host.process(2385, "SessionLeader", host.init, 2)
        self.assertIsNone(topology.wsl_runtime(rec(2385, "SessionLeader", host.init),
                                               host.topo()))

    @as_root
    def test_copy_of_init_elsewhere_is_not_the_runtime(self):
        # init_replacement: identical name and bytes, different file identity.
        fake_init = self.host.binary("init")
        self.host.process(3000, "SessionLeader", fake_init, 2)
        p = rec(3000, "SessionLeader", fake_init)
        topo = self.host.topo()
        self.assertIsNone(topology.wsl_runtime(p, topo))
        self.assertIn("name-mismatch", detect.traits(p, topo))

    @as_root
    def test_record_claiming_init_but_running_other_file_is_not_explained(self):
        other = self.host.binary("payload")
        self.host.process(3001, "SessionLeader", other, 2)
        p = rec(3001, "SessionLeader", self.host.init)   # the record lies
        self.assertIsNone(topology.wsl_runtime(p, self.host.topo()))

    @as_root
    def test_unknown_alias_from_init_is_not_explained(self):
        self.host.process(3002, "sshd", self.host.init, 2)
        p = rec(3002, "sshd", self.host.init)
        self.assertIsNone(topology.wsl_runtime(p, self.host.topo()))

    @as_root
    def test_non_init_ancestor_breaks_the_proof(self):
        shell = self.host.binary("bash")
        self.host.process(400, "bash", shell, 0)
        self.host.process(3003, "SessionLeader", self.host.init, 400)
        p = rec(3003, "SessionLeader", self.host.init)
        self.assertIsNone(topology.wsl_runtime(p, self.host.topo()))

    @as_root
    def test_non_root_runtime_claim_is_not_explained(self):
        self.host.process(3004, "SessionLeader", self.host.init, 2, uid=1000)
        p = rec(3004, "SessionLeader", self.host.init, user="chris")
        self.assertIsNone(topology.wsl_runtime(p, self.host.topo()))

    @as_root
    def test_writable_init_mount_disables_the_proof(self):
        host = FakeHost(self, init_mount="rw")
        host.process(2, "init", host.init, 0)
        host.process(5, "SessionLeader", host.init, 2)
        self.assertIsNone(topology.wsl_runtime(rec(5, "SessionLeader", host.init), host.topo()))

    def test_init_not_owned_by_root_disables_the_proof(self):
        # No as_root: the fake /init belongs to the test user.
        if os.getuid() == 0:
            self.skipTest("running as root")
        p = rec(2385, "SessionLeader", self.host.init)
        self.assertIsNone(topology.wsl_runtime(p, self.host.topo()))

    @as_root
    def test_not_wsl_means_no_explanation(self):
        host = FakeHost(self, osrelease="6.8.0-generic")
        host.process(2, "init", host.init, 0)
        host.process(5, "SessionLeader", host.init, 2)
        topo = host.topo()
        self.assertFalse(topo.on_wsl)
        self.assertIsNone(topology.name_explanation(rec(5, "SessionLeader", host.init), topo))

    @as_root
    def test_unreadable_proc_entry_keeps_the_mismatch(self):
        p = rec(9999, "SessionLeader", self.host.init)       # no /proc/9999
        self.assertIn("name-mismatch", detect.traits(p, self.host.topo()))

    def test_without_topology_behaviour_is_unchanged(self):
        p = rec(2385, "SessionLeader", "/init")
        self.assertIn("name-mismatch", detect.traits(p))


class NameExplanationTests(unittest.TestCase):
    def setUp(self):
        self.host = FakeHost(self)

    @as_root
    def test_argv0_link_to_the_same_file(self):
        udevadm = self.host.binary("udevadm")
        link = os.path.join(self.host.bin, "systemd-udevd")
        os.symlink(udevadm, link)
        self.host.process(111, "systemd-udevd", udevadm, 1)
        with mock.patch.object(topology, "TRUSTED_EXE_PREFIXES", (self.host.bin + "/",)):
            p = rec(111, "systemd-udevd", udevadm, cmdline=link)
            self.assertIn("argv0-link", topology.name_explanation(p, self.host.topo()))

    @as_root
    def test_argv0_naming_a_different_file_is_not_a_link(self):
        real = self.host.binary("worker")
        decoy = self.host.binary("systemd-udevd")
        self.host.process(112, "systemd-udevd", real, 1)
        p = rec(112, "systemd-udevd", real, cmdline=decoy)
        self.assertIsNone(topology.name_explanation(p, self.host.topo()))

    @as_root
    def test_shebang_script_under_system_path(self):
        py = self.host.binary("python3.12")
        self.host.process(317, "unattended-upgr", py, 1)
        script = "/usr/share/unattended-upgrades/unattended-upgrade-shutdown"
        p = rec(317, "unattended-upgr", py, cmdline=f"/usr/bin/python3 {script}",
                script=script)
        self.assertIn("shebang", topology.name_explanation(p, self.host.topo()))

    @as_root
    def test_script_named_like_a_system_binary_outside_system_paths_stays_flagged(self):
        # script_collision: /home/x/sshd run through its shebang.
        py = self.host.binary("python3.12")
        self.host.process(318, "sshd", py, 1)
        p = rec(318, "sshd", py, cmdline=f"{py} /home/x/sshd", script="/home/x/sshd")
        with mock.patch.object(topology, "_collides_with_system_binary",
                               side_effect=lambda name: name == "sshd"):
            self.assertIsNone(topology.name_explanation(p, self.host.topo()))
            self.assertIn("name-mismatch", detect.traits(p, self.host.topo()))

    @as_root
    def test_systemd_helper_of_a_trusted_binary(self):
        executor = self.host.binary("systemd-executor")
        self.host.process(324, "(sd-pam)", executor, 321, uid=1000)
        with mock.patch.object(topology, "TRUSTED_EXE_PREFIXES", (self.host.bin + "/",)):
            p = rec(324, "(sd-pam)", executor, cmdline="(sd-pam)", user="chris")
            self.assertIn("helper", topology.name_explanation(p, self.host.topo()))

    @as_root
    def test_parenthesized_name_from_a_world_writable_directory_stays_flagged(self):
        # prctl_rename: a dropped payload calling itself "(sd-pam)".
        dropped = self.host.binary("x")
        self.host.process(900, "(sd-pam)", dropped, 1, uid=1000)
        p = rec(900, "(sd-pam)", dropped, cmdline="(sd-pam)", user="chris")
        self.assertIsNone(topology.name_explanation(p, self.host.topo()))   # untrusted path
        self.assertIn("name-mismatch", detect.traits(p, self.host.topo()))

    @as_root
    def test_group_writable_helper_binary_stays_flagged(self):
        exe = self.host.binary("udevadm", mode=0o775)
        self.host.process(901, "(udev-worker)", exe, 111)
        with mock.patch.object(topology, "TRUSTED_EXE_PREFIXES", (self.host.bin + "/",)):
            p = rec(901, "(udev-worker)", exe, cmdline="(udev-worker)")
            self.assertIsNone(topology.name_explanation(p, self.host.topo()))

    @as_root
    def test_deleted_executable_is_never_explained(self):
        exe = self.host.binary("udevadm")
        self.host.process(902, "(udev-worker)", exe, 111)
        p = rec(902, "(udev-worker)", exe + " (deleted)", cmdline="(udev-worker)")
        self.assertIsNone(topology.name_explanation(p, self.host.topo()))

    @as_root
    def test_reused_pid_is_not_explained(self):
        exe = self.host.binary("udevadm")
        self.host.process(903, "(udev-worker)", exe, 111)
        # The record was taken from a different process that had this pid.
        p = rec(903, "(evil)", "/home/x/evil", cmdline="(evil)")
        self.assertIsNone(topology.name_explanation(p, self.host.topo()))

    def _exited_helper(self, mode):
        # A udev worker gone before assessment: no /proc entry, only the
        # identity linux.collect recorded with the exe link.
        exe = "/usr/bin/udevadm"
        return rec(990, "(udev-worker)", exe, cmdline="(udev-worker)") | {
            "exe_ident": (2096, 328902, 0, stat.S_IFREG | mode)}

    def test_exited_helper_is_explained_by_its_recorded_identity(self):
        self.assertIn("helper", topology.name_explanation(self._exited_helper(0o755),
                                                          self.host.topo()))

    def test_recorded_writable_or_foreign_identity_is_not_explained(self):
        topo = self.host.topo()
        self.assertIsNone(topology.name_explanation(self._exited_helper(0o777), topo))
        foreign = self._exited_helper(0o755)
        foreign["exe_ident"] = (2096, 328902, 1000, stat.S_IFREG | 0o755)
        self.assertIsNone(topology.name_explanation(foreign, topo))

    def test_exited_process_without_recorded_identity_fails_closed(self):
        for ident in (None, ("a", 1, 0, 0o755), (1, 2, 3)):
            with self.subTest(ident=ident):
                p = self._exited_helper(0o755)
                p["exe_ident"] = ident
                self.assertIsNone(topology.name_explanation(p, self.host.topo()))

    def test_collect_records_the_exe_identity_with_the_link(self):
        # Our own child is always readable. Other processes may not be: under
        # the root deploy the suite's parent is root's python, whose exe link
        # is unreadable, so exe is '' and no identity may be recorded.
        from jarvis.platform import linux
        child = subprocess.Popen(["/bin/sleep", "30"])
        self.addCleanup(child.wait)
        self.addCleanup(child.kill)
        procs = linux.collect(with_sockets=False)
        mine = [p for p in procs if p["pid"] == child.pid]
        self.assertEqual(len(mine), 1)
        st = os.stat(mine[0]["exe"])
        self.assertEqual(mine[0]["exe_ident"][:2], (st.st_dev, st.st_ino))
        for p in procs:
            if not p["exe"]:
                self.assertIsNone(p["exe_ident"])

    def test_windows_records_are_never_explained(self):
        p = {**rec(4, "svchost", "c:/users/x/svc.exe"), "host": "win"}
        self.assertIsNone(topology.name_explanation(p, self.host.topo()))


class DnsTunnelTests(unittest.TestCase):
    BASE = {"proto": "udp", "local_ip": "10.255.255.254", "local_port": 53,
            "remote_ip": "0.0.0.0", "remote_port": 0, "state": "-",
            "_verification": "confirmed", "_fd_visibility": "complete"}

    def setUp(self):
        self.host = FakeHost(self)

    def test_declared_tunnel_is_low_with_its_proof(self):
        f = _orphan_finding(self.BASE, True, self.host.topo())
        self.assertEqual(f["severity"], "low")
        self.assertIn("resolv.conf", f["detail"])

    def test_every_missing_proof_element_keeps_medium(self):
        topo = self.host.topo()
        for change in ({"_fd_visibility": "limited"}, {"_verification": "inconclusive"},
                       {"local_port": 5353}, {"local_ip": "127.0.0.1"}):
            with self.subTest(change=change):
                f = _orphan_finding({**self.BASE, **change}, True, topo)
                self.assertEqual(f["severity"], "medium")

    def test_undeclared_loopback_listener_stays_medium(self):
        f = _orphan_finding({**self.BASE, "local_ip": "127.0.0.1", "local_port": 323},
                            True, self.host.topo())
        self.assertEqual(f["severity"], "medium")

    def test_user_managed_resolv_conf_declares_nothing(self):
        with open(os.path.join(self.host.etc, "resolv.conf"), "w") as fh:
            fh.write("nameserver 10.255.255.254\n")
        self.assertEqual(_orphan_finding(self.BASE, True, self.host.topo())["severity"],
                         "medium")

    def test_declared_address_not_routed_locally_is_not_the_tunnel(self):
        with open(os.path.join(self.host.proc, "net", "fib_trie"), "w") as fh:
            fh.write("Main:\n     |-- 127.0.0.1\n        /32 host LOCAL\n")
        self.assertEqual(_orphan_finding(self.BASE, True, self.host.topo())["severity"],
                         "medium")

    def test_peer_connection_on_tunnel_address_stays_high(self):
        f = _orphan_finding({**self.BASE, "remote_ip": "203.0.113.9", "remote_port": 4444,
                             "state": "ESTABLISHED", "proto": "tcp"}, True, self.host.topo())
        self.assertEqual(f["severity"], "high")

    def test_unreadable_facts_give_no_tunnel(self):
        os.remove(os.path.join(self.host.proc, "net", "fib_trie"))
        os.remove(os.path.join(self.host.etc, "resolv.conf"))
        self.assertEqual(self.host.topo().dns_tunnel, frozenset())


class SnapshotTests(unittest.TestCase):
    def test_missing_mountinfo_means_runtime_not_provable(self):
        host = FakeHost(self)
        os.remove(os.path.join(host.proc, "self", "mountinfo"))
        self.assertFalse(host.topo().wsl_runtime_provable)

    def test_mode_bits_require_no_group_or_other_write(self):
        self.assertTrue(topology._root_owned_readonly((1, 2, 0, stat.S_IFREG | 0o755)))
        self.assertFalse(topology._root_owned_readonly((1, 2, 0, stat.S_IFREG | 0o775)))
        self.assertFalse(topology._root_owned_readonly((1, 2, 1000, stat.S_IFREG | 0o755)))
        self.assertFalse(topology._root_owned_readonly(None))


