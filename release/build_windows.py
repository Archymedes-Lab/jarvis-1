#!/usr/bin/env python3
"""Build the ARGUS-INSTINCT Windows engine as a native program: no source, no bytecode.

    python release/build_windows.py --version V --out DIR [--ref HEAD] [--jobs 4]

Runs on the clean windows-2025 runner (.github/workflows/release.yml). Steps:

  1. export the commit and rename jarvis -> argus (release/rename.py);
  2. compile every PowerShell payload into the program: argus/core/_payloads.py
     holds their exact bytes and a digest of the set (core/paths.py reads it;
     the compiled copy wins over any file of the same name), so the download
     carries no .ps1 file;
  3. compile the package and release/launcher.py with Nuitka into a standalone
     folder, engine/argus-instinct.exe plus the DLLs it needs and the package's
     data files, with Windows version information;
  4. smoke-test the program: --help, -m refusal, a payload run through
     PowerShell (`native status`), and its own verification;
  5. pack argus-instinct-windows-x64.zip with fixed timestamps and run the
     content gate over it.

The per-user installer (ARGUS-INSTINCT-Setup-windows-x64.exe) is made from this
zip and the desktop app by release/build_setup.py.
"""

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_server  # noqa: E402
import gate  # noqa: E402
import rename  # noqa: E402

ZIP_NAME = "argus-instinct-windows-x64.zip"
TOP = "ARGUS-INSTINCT"
EXE = "argus-instinct.exe"
ZIP_TIME = (2026, 1, 1, 0, 0, 0)
# Repository-level scripts the Windows edition runs (paths after the rename).
# The native service loop is what Task Scheduler starts; collectors' payloads
# live in argus/platform/win.
REPO_SCRIPTS = ("argus-native-service.ps1",)
# Repository-level data the Windows collectors read through REPO_ROOT.
REPO_DATA = ("windows-sysmon/argus-windows-baseline.xml",)


def file_version(version):
    """'2026.11.03-2' -> '2026.11.3.2' (Windows wants four numbers)."""
    m = re.fullmatch(r"(\d{4})\.(\d{2})\.(\d{2})(?:-(\d+))?", version)
    if not m:
        raise ValueError(f"version {version!r} is not YYYY.MM.DD[-N]")
    y, mo, d, n = m.groups()
    return f"{int(y)}.{int(mo)}.{int(d)}.{int(n or 0)}"


def payload_module(tree):
    """Write tree/argus/core/_payloads.py; returns (names, digest)."""
    found = {}
    for f in sorted((tree / "argus" / "platform" / "win").glob("*.ps1")):
        found[f.name] = f.read_bytes()
    for rel in REPO_SCRIPTS:
        f = tree / rel
        if not f.is_file():
            sys.exit(f"{rel} is missing from the export")
        if f.name in found:
            sys.exit(f"two payloads are named {f.name}")
        found[f.name] = f.read_bytes()
    if not found:
        sys.exit("no PowerShell payloads found")
    h = hashlib.sha256()
    for name in sorted(found):
        h.update(name.encode() + b"\0" + hashlib.sha256(found[name]).digest())
    digest = h.hexdigest()
    lines = ['"""Generated by release/build_windows.py: the PowerShell payloads, compiled in."""', "",
             f"DIGEST = {digest!r}", "SCRIPTS = {"]
    lines += [f"    {name!r}: {data!r}," for name, data in sorted(found.items())]
    lines += ["}", ""]
    (tree / "argus" / "core" / "_payloads.py").write_text("\n".join(lines), encoding="utf-8")
    return sorted(found), digest


def nuitka(tree, work, jobs, version):
    """Compile tree/release/launcher.py; returns the standalone folder."""
    fv = file_version(version)
    cmd = [sys.executable, "-m", "nuitka", "--standalone", "--assume-yes-for-downloads",
           f"--output-dir={work}", f"--output-filename={EXE}",
           "--include-package=argus", "--nofollow-import-to=argus.platform.win",
           "--include-module=argus.core._payloads",
           "--include-package=cryptography",
           "--python-flag=isolated", "--python-flag=safe_path", "--python-flag=unbuffered",
           "--file-reference-choice=runtime", "--lto=no", f"--jobs={jobs}",
           f"--report={work}/nuitka-report.xml", "--remove-output",
           "--no-deployment-flag=self-execution",
           "--include-module=_json", "--include-module=_bisect",
           # The service runs it hidden; a person running it from a terminal sees its output.
           "--windows-console-mode=attach",
           "--company-name=Archymedes", "--product-name=ARGUS-INSTINCT",
           "--file-description=ARGUS-INSTINCT engine", f"--file-version={fv}", f"--product-version={fv}",
           f"--copyright=Copyright Archymedes {version[:4]}"]
    icon = tree / "desktop" / "icons" / "icon.ico"
    if icon.is_file():
        cmd.append(f"--windows-icon-from-ico={icon}")
    for f, rel in build_server.data_files(tree, Path(work) / "data-clean"):
        cmd.append(f"--include-data-files={f}={rel}")
    for rel in REPO_DATA:
        if not (tree / rel).is_file():
            sys.exit(f"{rel} is missing from the export")
        cmd.append(f"--include-data-files={tree / rel}={rel}")
    cmd.append(str(tree / "release" / "launcher.py"))
    print("$ " + " ".join(cmd[:12]) + " ...", flush=True)
    subprocess.run(cmd, cwd=tree, check=True)
    dist = work / "launcher.dist"
    if not (dist / EXE).is_file():
        sys.exit(f"Nuitka produced no {dist / EXE}")
    return dist


def smoke(dist, digest):
    """The program starts, refuses arbitrary -m modules, runs a compiled payload
    through PowerShell, writes it out under the given profile, and passes its own checks."""
    scratch = Path(tempfile.mkdtemp(prefix="argus-smoke-"))
    env = {**os.environ, "ARGUS_QUIET_SEAL": "1", "USERPROFILE": str(scratch), "HOME": str(scratch),
           "LOCALAPPDATA": str(scratch / "Local"), "APPDATA": str(scratch / "Roaming")}
    exe = str(dist / EXE)

    def run(args, timeout=300):
        return subprocess.run([exe, *args], capture_output=True, text=True, errors="replace",
                              env=env, timeout=timeout)

    r = run(["--help"])
    if r.returncode != 0:
        sys.exit(f"{EXE} --help failed:\n{r.stdout}{r.stderr}")
    if run(["-m", "os"], timeout=60).returncode != 2:
        sys.exit(f"{EXE} ran an arbitrary -m module")
    r = run(["native", "status"], timeout=120)
    written = scratch / "Local" / "Argus" / "Payload" / digest[:16] / "argus-native-service.ps1"
    if "daemon process:" not in r.stdout + r.stderr or not written.is_file():
        sys.exit(f"the compiled supervisor payload did not run:\n{(r.stdout + r.stderr)[-3000:]}")
    if any(p.suffix in (".py", ".pyc", ".ps1", ".cs") for p in dist.rglob("*")):
        sys.exit("source or script files are left in the program folder")
    report = scratch / "verification.json"
    r = run(["-m", "argus.verify", "--json", str(report)], timeout=900)
    if r.returncode != 0:
        sys.exit(f"the compiled program fails its own verification:\n{(r.stdout + r.stderr)[-3000:]}")
    return json.loads(report.read_text())


def readme(version, commit):
    return (f"ARGUS-INSTINCT {version} for Windows (x64), commit {commit}\r\n\r\n"
            "Install: run ARGUS-INSTINCT-Setup-windows-x64.exe (per user, no administrator).\r\n"
            "This zip is the same engine for a manual install:\r\n"
            "  engine\\argus-instinct.exe native install     start the per-user service\r\n"
            "  engine\\argus-instinct.exe native status --all what runs here and what does not apply\r\n"
            "  engine\\argus-instinct.exe welcome desktop    what it watches, its limits, how to remove it\r\n"
            "  engine\\argus-instinct.exe native uninstall   stop and remove (your history stays)\r\n"
            "Not in this edition: the elevated sensor service and the elevated broker.\r\n").encode()


def entries(dist, version, commit):
    out = []
    for f in sorted(dist.rglob("*")):
        if f.is_symlink():
            sys.exit(f"{f}: the program folder must hold no links")
        if f.is_file():
            out.append((f"{TOP}/engine/{f.relative_to(dist).as_posix()}", f.read_bytes()))
    out.append((f"{TOP}/README.txt", readme(version, commit)))
    out.append((f"{TOP}/VERSION", f"{version} ({commit})\r\n".encode()))
    return out


def build_zip(files, out):
    path = out / ZIP_NAME
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name, data in files:
            info = zipfile.ZipInfo(name, ZIP_TIME)
            info.external_attr = 0o644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, data)
    return ZIP_NAME


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--version", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--ref", default="HEAD")
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--work", help="build folder (default: a temporary one)")
    args = ap.parse_args()
    # The runner's console is cp1252: a refusal quoting an odd byte must print, not crash.
    sys.stdout.reconfigure(errors="replace")
    sys.stderr.reconfigure(errors="replace")
    file_version(args.version)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="argus-windows-") as tmp:
        work = Path(args.work or tmp)
        tree = work / "tree"
        shutil.rmtree(tree, ignore_errors=True)
        commit = rename.export(HERE.parent, args.ref, tree)
        names, digest = payload_module(tree)
        print(f"exported {commit} as Argus; {len(names)} payloads compiled in (set {digest[:16]})", flush=True)
        dist = nuitka(tree, work / "nuitka", args.jobs, args.version)
        shutil.copy(work / "nuitka" / "nuitka-report.xml", out / "windows-nuitka-report.xml")
        verification = smoke(dist, digest)
        print(f"compiled program passes its own verification: {verification.get('ok', verification)!s:.200}")
        built = [build_zip(entries(dist, args.version, commit), out)]
    record = {"edition": "windows", "version": args.version, "commit": commit, "payload_digest": digest,
              "payloads": names,
              "files": {n: {"bytes": (out / n).stat().st_size,
                            "sha256": hashlib.sha256((out / n).read_bytes()).hexdigest()} for n in built}}
    (out / "windows-build.json").write_text(json.dumps(record, indent=2) + "\n")
    policy = gate.load_policy()
    problems = []
    for name in built:
        problems += gate.check_artifact(out / name, gate.rule_for(name, policy), policy)[0]
    for p in problems:
        print("REFUSED  " + p)
    if problems:
        # Every distinct match in each refused file, so one run shows the whole picture.
        with zipfile.ZipFile(out / ZIP_NAME) as z:
            for name in sorted({p.split(":", 2)[1] for p in problems if p.count(":") >= 2}):
                try:
                    found = gate.marker_texts(z.read(name), policy)
                except KeyError:
                    continue
                if found:
                    print(f"MATCHES  {name}: {json.dumps(found)}")
        sys.exit(f"the Windows engine fails the content gate ({len(problems)} problems)")
    print("Windows engine passes the content gate: " + ", ".join(built))


if __name__ == "__main__":
    main()
